let currentLanguage = 'en';
const langSwitch = document.getElementById('langSwitch');
const langLabel = document.getElementById('langLabel');

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (!translations[language][key]) return;
    if (key === 'profile.experienceText') {
      element.innerHTML = translations[language][key];
    } else {
      element.textContent = translations[language][key];
    }
  });
  langLabel.textContent = language === 'en' ? 'ES' : 'EN';
  localStorage.setItem('portfolio-language', language);
}

langSwitch.addEventListener('click', () => {
  applyLanguage(currentLanguage === 'en' ? 'es' : 'en');
});

const savedLanguage = localStorage.getItem('portfolio-language');
applyLanguage(savedLanguage === 'es' ? 'es' : 'en');

const avatarSwitch = document.getElementById('avatarSwitch');
const profileAvatar = document.getElementById('profileAvatar');
let skinActive = false;

avatarSwitch.addEventListener('click', () => {
  skinActive = !skinActive;
  profileAvatar.src = skinActive ? 'Assets/Images/profile-skin.png' : 'Assets/Images/profile-photo.jpg';
  profileAvatar.alt = skinActive ? 'Minecraft-style version of Elian Gonzalez' : 'Elian Gonzalez profile photo';
});

const copyEmail = document.getElementById('copyEmail');
const copyStatus = document.getElementById('copyStatus');
const emailAddress = 'elian.gonzalez05@gmail.com';

copyEmail.addEventListener('click', async () => {
  try {
    await navigator.clipboard.writeText(emailAddress);
    copyStatus.textContent = translations[currentLanguage]['copy.ok'];
  } catch (error) {
    copyStatus.textContent = translations[currentLanguage]['copy.fail'];
  }
});

const contactForm = document.getElementById('contactForm');
contactForm.addEventListener('submit', (event) => {
  event.preventDefault();
  const name = document.getElementById('contactName').value.trim();
  const email = document.getElementById('contactEmail').value.trim();
  const message = document.getElementById('contactMessage').value.trim();
  const subject = encodeURIComponent(`Portfolio contact - ${name}`);
  const body = encodeURIComponent(`${message}\n\nFrom: ${name}\nEmail: ${email}`);
  window.location.href = `mailto:${emailAddress}?subject=${subject}&body=${body}`;
});
